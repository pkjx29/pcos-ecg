"""Synthetic ECG-like recordings for demos and tests.

Each beat is a sum of five Gaussians (P, Q, R, S, T), in the spirit of McSharry et al.
(2003, IEEE TBME 50:289) but much simpler. Noise, baseline wander and 50 Hz mains hum
are added so the filters have something to remove.

The "positive" class is given a slightly higher heart rate, lower heart-rate variability
and longer QTc. These effect sizes are ARBITRARY: they are not taken from the literature
or from the RIT study, and nothing learned from this data says anything about PCOS.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

SYNTHETIC_NOTICE = (
    "SYNTHETIC DEMO DATA - generated by pcos_ecg.demo.synthetic; no real participants; "
    "class differences are arbitrary and carry no clinical meaning."
)


@dataclass
class SubjectParams:
    heart_rate_bpm: float
    sdnn_s: float
    qtc_s: float
    pr_s: float
    r_amp_mv: float


def synth_ecg(
    params: SubjectParams,
    duration_s: float,
    fs: float,
    rng: np.random.Generator,
    noise_mv: float = 0.02,
    wander_mv: float = 0.10,
    mains_mv: float = 0.03,
    mains_hz: float = 50.0,
) -> tuple[np.ndarray, np.ndarray]:
    """Return (signal_mv, true_r_peak_indices) for one recording."""
    n = int(round(duration_s * fs))
    t = np.arange(n) / fs
    sig = np.zeros(n)

    mean_rr = 60.0 / params.heart_rate_bpm
    r_times = []
    tr = 0.4
    while tr < duration_s - 0.6:
        r_times.append(tr)
        rr = max(0.3, rng.normal(mean_rr, params.sdnn_s))
        tr += rr

    for i, r in enumerate(r_times):
        rr = (r_times[i] - r_times[i - 1]) if i > 0 else mean_rr
        qt = params.qtc_s * np.sqrt(rr)  # Bazett, inverted
        # (centre offset from R in s, amplitude in mV, width in s)
        waves = [
            (0.01 - params.pr_s, 0.15, 0.025),  # P: onset ~ 2 widths before centre
            (-0.03, -0.12, 0.010),  # Q
            (0.0, params.r_amp_mv, 0.012),  # R
            (0.03, -0.25, 0.010),  # S
            (qt - 0.04 - 0.10, 0.30, 0.045),  # T: ends ~2 widths after centre
        ]
        lo, hi = int((r - 0.4) * fs), int((r + 0.6) * fs)
        seg = slice(max(lo, 0), min(hi, n))
        for c, a, w in waves:
            sig[seg] += a * np.exp(-((t[seg] - (r + c)) ** 2) / (2 * w**2))

    sig += rng.normal(0, noise_mv, n)
    sig += wander_mv * np.sin(2 * np.pi * 0.3 * t + rng.uniform(0, 2 * np.pi))
    sig += mains_mv * np.sin(2 * np.pi * mains_hz * t)
    peaks = np.round(np.array(r_times) * fs).astype(int)
    return sig, peaks


def make_demo_cohort(
    n_subjects: int = 30,
    n_positive: int = 10,
    records_per_subject: int = 2,
    duration_s: float = 30.0,
    fs: float = 250.0,
    seed: int = 7,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Build a synthetic cohort. Returns (long-form waveforms, participant labels)."""
    if not 0 < n_positive < n_subjects:
        raise ValueError("n_positive must be between 1 and n_subjects - 1")
    rng = np.random.default_rng(seed)
    labels = np.array([1] * n_positive + [0] * (n_subjects - n_positive))
    rng.shuffle(labels)

    frames, label_rows = [], []
    for s, y in enumerate(labels):
        sid = f"SYN{s:03d}"
        base = SubjectParams(
            heart_rate_bpm=rng.normal(72 + 6 * y, 7),
            sdnn_s=abs(rng.normal(0.045 - 0.012 * y, 0.01)) + 0.01,
            qtc_s=rng.normal(0.405 + 0.015 * y, 0.015),
            pr_s=rng.normal(0.16, 0.015),
            r_amp_mv=rng.normal(1.1, 0.15),
        )
        for r in range(records_per_subject):
            p = SubjectParams(
                heart_rate_bpm=base.heart_rate_bpm + rng.normal(0, 2),
                sdnn_s=base.sdnn_s,
                qtc_s=base.qtc_s + rng.normal(0, 0.005),
                pr_s=base.pr_s,
                r_amp_mv=base.r_amp_mv,
            )
            sig, _ = synth_ecg(p, duration_s, fs, rng)
            frames.append(
                pd.DataFrame(
                    {
                        "subject_id": sid,
                        "record_id": f"{sid}-R{r}",
                        "lead": "I",
                        "sample_index": np.arange(sig.size),
                        "sample_rate_hz": fs,
                        "amplitude": np.round(sig, 5),
                    }
                )
            )
        label_rows.append({"subject_id": sid, "label": int(y)})
    return pd.concat(frames, ignore_index=True), pd.DataFrame(label_rows)


def make_demo_covariates(labels: pd.DataFrame, seed: int = 7) -> pd.DataFrame:
    """The study's four physiological features for the synthetic participants.

    Class differences are arbitrary, like the ECG ones: they exist only so the demo has
    something to find, and say nothing about real PCOS.
    """
    rng = np.random.default_rng(seed + 1)
    rows = []
    for sid, y in zip(labels["subject_id"], labels["label"], strict=True):
        rows.append(
            {
                "subject_id": sid,
                "Cycle_Length": round(float(rng.normal(36 if y else 29, 6 if y else 3)), 1),
                "Cycle_Regularity": "Irregular"
                if rng.random() < (0.6 if y else 0.2)
                else "Regular",
                "BMI": round(float(rng.normal(25.5 if y else 22.5, 3.5)), 1),
                "Family_History": "Yes" if rng.random() < (0.4 if y else 0.15) else "No",
            }
        )
    return pd.DataFrame(rows)


def write_demo_cohort(out_dir: str | Path, **kwargs) -> tuple[Path, Path, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    wave, labels = make_demo_cohort(**kwargs)
    wave_path, label_path, cov_path = (
        out / "ecg_long.csv",
        out / "labels.csv",
        out / "covariates.csv",
    )
    wave.to_csv(wave_path, index=False)
    labels.to_csv(label_path, index=False)
    make_demo_covariates(labels, seed=kwargs.get("seed", 7)).to_csv(cov_path, index=False)
    (out / "README.txt").write_text(SYNTHETIC_NOTICE + "\n")
    return wave_path, label_path, cov_path
